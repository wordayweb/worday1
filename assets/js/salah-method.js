let currentTab = 'fard';

function toAr(s) {
  return String(s).replace(/[0-9]/g, d => ['٠','١','٢','٣','٤','٥','٦','٧','٨','٩'][d]);
}

function renderTab(tabKey) {
  const container = document.getElementById('salahStepsContainer');
  if (!container) return;
  container.innerHTML = '';

  const data = SALAH_DATA[tabKey];
  if (!data) return;

  if (data.intro) {
    const intro = document.createElement('div');
    intro.className = 'tab-intro';
    intro.textContent = data.intro;
    container.appendChild(intro);
  }

  data.steps.forEach((step, index) => {
    const card = document.createElement('div');
    card.className = 'step-card';
    card.id = `step-${tabKey}-${index}`;

    card.innerHTML = `
      <div class="step-header" onclick="toggleStep('step-${tabKey}-${index}')">
        <div class="step-number">${toAr(index + 1)}</div>
        <h4 class="step-title">${step.title}</h4>
        <div class="step-toggle">▼</div>
      </div>
      <div class="step-content">
        <div class="step-body">
          ${step.desc ? `<p class="step-description">${step.desc}</p>` : ''}
          <div class="step-arabic">${step.arabic}</div>
          ${step.hadith ? `<div class="step-hadith"><strong>📚 الحديث:</strong>${step.hadith}</div>` : ''}
          ${step.note ? `<div class="step-note"><span class="note-icon">💡</span><span>${step.note}</span></div>` : ''}
        </div>
      </div>
    `;

    container.appendChild(card);
  });
}

function toggleStep(id) {
  const card = document.getElementById(id);
  if (!card) return;
  card.classList.toggle('active');
}

function expandAll() {
  const cards = document.querySelectorAll('.step-card');
  const allActive = Array.from(cards).every(c => c.classList.contains('active'));
  cards.forEach(c => {
    if (allActive) c.classList.remove('active');
    else c.classList.add('active');
  });
  const btn = document.getElementById('expandAllBtn');
  if (btn) btn.textContent = allActive ? '📖' : '📕';
}

function switchTab(tabKey) {
  currentTab = tabKey;
  document.querySelectorAll('.tab-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.tab === tabKey);
    btn.setAttribute('aria-selected', btn.dataset.tab === tabKey);
  });
  renderTab(tabKey);
  window.scrollTo({ top: 300, behavior: 'smooth' });
}

document.addEventListener('DOMContentLoaded', () => {
  renderTab('fard');

  document.querySelectorAll('.tab-btn').forEach(btn => {
    btn.addEventListener('click', () => switchTab(btn.dataset.tab));
  });

  const expandBtn = document.getElementById('expandAllBtn');
  if (expandBtn) expandBtn.addEventListener('click', expandAll);
});
